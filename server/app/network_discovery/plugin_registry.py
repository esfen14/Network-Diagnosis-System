"""
Plugin registry for the Nagios configuration generated by Network Discovery.

Every monitored service is resolved from a PLUGIN NAME (snmp, ncpa, http, ...)
to a PluginDefinition — never from a port. A port is just one of the plugin's
variables: defaulted by the definition, replaced by the port the service was
actually discovered on, and overridable per host.

Resolution order
----------------
    discovered service name ──► plugin name   (name/alias match, else the
            │                                  generic "tcp" plugin; unmatched
            │                                  UDP ports are skipped)
            ▼
    PluginDefinition ──► transports, variables, checks, command layout
            │
            ▼
    variables = definition defaults
              < app config defaults   (e.g. SNMP_COMMUNITY_STRING, SNMP_OIDS)
              < discovery facts       (port found on, NCPA token, partitions)
              < host overrides        (NetworkDiscovery.Plugin_Variables)
            │
            ▼
    checks(variables) ──► one ServiceCheck per metric (SNMP OID, NCPA metric…)
            │
            ▼
    resolve_plugin_command() ──► "pinpoint_nd_snmp!161!public!1.3.6.1…!"

Each definition renders its own Nagios `define command` object named
pinpoint_nd_<plugin>, so generated configs never depend on which commands
happen to exist in the stock commands.cfg. The pinpoint_nd_ prefix keeps
them distinct from Plugin Manager's own pinpoint_<plugin> commands (see
app/api/plugin/monitoring_config.py).

Adding a plugin — including one that produces many services — only means
adding a PluginDefinition to PLUGIN_DEFINITIONS. Neither the resolver nor
the config generator needs to change.

Security: every variable value ends up inside a Nagios object file and a
shell-executed command line. Values are single-quoted in the generated
command_line and any character that could escape that quoting, split
Nagios arguments (!), expand a macro ($) or start a cfg comment (;) is
rejected. Error messages name the offending variable, never its value, so
secrets such as the NCPA token are not leaked into logs.
"""
import re
from dataclasses import dataclass, field
from enum import Enum
from typing import Callable, Optional

COMMAND_NAME_PREFIX = "pinpoint_nd_"

# Characters that could break out of a single-quoted shell argument, split
# Nagios' "!" argument list, expand a Nagios macro, or start a cfg comment.
FORBIDDEN_VALUE_CHARACTERS = frozenset("'\"`!$;\\\n\r\0")

# Characters Nagios refuses in object names (illegal_object_name_chars
# default), plus whitespace, which would make service names awkward to use.
ILLEGAL_NAME_CHARACTERS = re.compile(r"[`~!$%^&*|'\"<>?,()=\s]")

COMMAND_TEMPLATE = """define command {{
    command_name    {command_name}
    command_line    {command_line}
}}
"""


class Transport(Enum):
    TCP = "TCP"
    UDP = "UDP"


class PluginConfigurationError(ValueError):
    """
    Raised when a plugin cannot be resolved into a valid Nagios command —
    unknown plugin, missing required variable, unsafe value, or a transport
    the plugin does not support. Messages never contain variable values.
    """


@dataclass(frozen=True)
class ServiceCheck:
    """
    One Nagios service produced by a plugin. metric is None for plugins that
    produce a single service (e.g. ssh); otherwise it names the data point
    (e.g. "uptime" for an SNMP OID, "cpu" for an NCPA metric). variables are
    layered on top of the plugin's resolved variables for this service only.
    """
    metric: Optional[str]
    variables: dict = field(default_factory=dict)


def single_check(variables):
    """
    Default checks provider: the plugin produces exactly one service using
    the plugin-level variables unchanged.
    """
    return [ServiceCheck(metric=None)]


def snmp_checks(variables):
    """
    One service per configured OID. Expects variables["oids"] to be a list of
    {"metric": ..., "oid": ...} dicts; any other key in an entry (warning,
    critical, label, units) is passed through as a per-service variable.
    """
    oids = variables.get("oids") or []
    if not isinstance(oids, list):
        raise PluginConfigurationError("SNMP variable 'oids' must be a list.")

    checks = []
    for entry in oids:
        if not isinstance(entry, dict) or not entry.get("oid") or not entry.get("metric"):
            raise PluginConfigurationError("Each SNMP OID entry needs an 'oid' and a 'metric'.")

        per_service = dict(entry)
        metric = per_service.pop("metric")
        checks.append(ServiceCheck(metric=metric, variables=per_service))
    return checks


def ncpa_checks(variables):
    """
    One service per configured NCPA metric. Expects variables["metrics"] to be
    a list of {"metric": ..., "path": ...} dicts. A path containing
    "{partition}" expands to one service per entry in variables["partitions"]
    (discovered during NCPA installation); if no partitions are known, the
    entry's "fallback_path" is used as a single service instead.
    """
    metrics = variables.get("metrics") or []
    partitions = variables.get("partitions") or []
    if not isinstance(metrics, list) or not isinstance(partitions, list):
        raise PluginConfigurationError("NCPA variables 'metrics' and 'partitions' must be lists.")

    checks = []
    for entry in metrics:
        if not isinstance(entry, dict) or not entry.get("path") or not entry.get("metric"):
            raise PluginConfigurationError("Each NCPA metric entry needs a 'path' and a 'metric'.")

        per_service = dict(entry)
        metric = per_service.pop("metric")
        path = per_service.pop("path")
        fallback_path = per_service.pop("fallback_path", None)

        if "{partition}" not in path:
            checks.append(ServiceCheck(metric=metric, variables={**per_service, "metric_path": path}))
        elif partitions:
            for partition in partitions:
                checks.append(ServiceCheck(
                    metric=f"{metric}_{partition}",
                    variables={**per_service, "metric_path": path.replace("{partition}", str(partition))},
                ))
        elif fallback_path:
            checks.append(ServiceCheck(metric=metric, variables={**per_service, "metric_path": fallback_path}))
    return checks


@dataclass(frozen=True)
class PluginDefinition:
    """
    Everything needed to turn a plugin name into Nagios services.

    arguments are (flag, variable) pairs that are always passed, in order, as
    $ARG1$..$ARGn$ — so every one of them is required. options map optional
    variables to their flag; whichever are set are rendered together into the
    final $ARG$. fixed_flags are literal flags every invocation needs.
    config_defaults map variable names to app config keys used as defaults.
    """
    name: str
    check_plugin: str
    transports: tuple
    arguments: tuple = ()
    options: dict = field(default_factory=dict)
    defaults: dict = field(default_factory=dict)
    config_defaults: dict = field(default_factory=dict)
    aliases: tuple = ()
    host_flag: str = "-H"
    fixed_flags: str = ""
    checks: Callable = single_check

    @property
    def command_name(self):
        return f"{COMMAND_NAME_PREFIX}{self.name}"

    @property
    def command_line(self):
        parts = [f"$USER1$/{self.check_plugin}", self.host_flag, "$HOSTADDRESS$"]
        if self.fixed_flags:
            parts.append(self.fixed_flags)
        for index, (flag, _variable) in enumerate(self.arguments, start=1):
            parts.append(f"{flag} '$ARG{index}$'")
        parts.append(f"$ARG{len(self.arguments) + 1}$")
        return " ".join(parts)


