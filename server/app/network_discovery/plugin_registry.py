GENERIC_PLUGIN_FOR_TRANSPORT = {
    Transport.TCP: "tcp",
    Transport.UDP: "udp",
}


# ==========================================================
# LOOKUPS
# ==========================================================

def get_plugin_definition(plugin_name):
    """
    Return the PluginDefinition registered under plugin_name (case-
    insensitive). Raises PluginConfigurationError if there is none.
    """
    definition = PLUGIN_DEFINITIONS.get(str(plugin_name).lower())
    if definition is None:
        raise PluginConfigurationError(f"Unknown plugin '{plugin_name}'.")
    return definition


def find_plugin_by_name_or_alias(name):
    """
    Return the PluginDefinition whose name or alias matches name
    (case-insensitive), or None.
    """
    key = str(name or "").lower().strip()
    if key in PLUGIN_DEFINITIONS:
        return PLUGIN_DEFINITIONS[key]
    for definition in PLUGIN_DEFINITIONS.values():
        if key in definition.aliases:
            return definition
    return None


def resolve_plugin_name(service_name, transport):
    """
    Map a discovered service name (nmap's guess, after the configured
    overrides) to a plugin name. The service must match a plugin's name or
    alias AND that plugin must support the transport it was found on;
    anything else is monitored by the transport's generic port-check plugin.
    """
    definition = find_plugin_by_name_or_alias(service_name)
    if definition is not None and transport in definition.transports:
        return definition.name
    return GENERIC_PLUGIN_FOR_TRANSPORT[transport]


def plugin_for_command(command_name):
    """
    Return the check plugin (e.g. "check_snmp") behind a Nagios command name
    reported by statusjson.cgi, or None if it is not one this registry
    generates. Arguments after "!" are ignored.
    """
    name = str(command_name or "").split("!")[0].strip()
    if not name.startswith(COMMAND_NAME_PREFIX):
        return None
    definition = PLUGIN_DEFINITIONS.get(name[len(COMMAND_NAME_PREFIX):])
    return definition.check_plugin if definition else None


