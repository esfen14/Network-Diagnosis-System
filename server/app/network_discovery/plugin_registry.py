def resolve_plugin_variables(plugin_name, app_config=None, discovered=None, overrides=None):
    """
    Merge a plugin's variables from lowest to highest precedence: definition
    defaults, app config defaults, discovery facts (e.g. the port the service
    was found on), then per-host overrides. Returns a new dict; inputs are
    not modified.
    """
    definition = get_plugin_definition(plugin_name)
    variables = dict(definition.defaults)

    for variable, config_key in definition.config_defaults.items():
        if app_config is not None and app_config.get(config_key) is not None:
            variables[variable] = app_config[config_key]

    for layer in (discovered, overrides):
        if layer:
            variables.update({key: value for key, value in layer.items() if value is not None})

    return variables


def validate_variable_value(variable, value):
    """
    Return value as a string if it is safe to place inside a Nagios command
    argument, otherwise raise PluginConfigurationError naming the variable.
    Ports must be integers between 1 and 65535.
    """
    text = str(value)

    if variable == "port":
        if not text.isdigit() or not 1 <= int(text) <= 65535:
            raise PluginConfigurationError("Variable 'port' must be an integer between 1 and 65535.")
        return str(int(text))

    if any(character in FORBIDDEN_VALUE_CHARACTERS for character in text):
        raise PluginConfigurationError(f"Variable '{variable}' contains a forbidden character.")
    return text


def resolve_plugin_command(plugin_name, variables, transport=None):
    """
    Build the Nagios check_command string for one service of plugin_name,
    e.g. "pinpoint_nd_snmp!161!public!1.3.6.1.2.1.1.3.0!".

    Validates that the plugin supports the requested transport, that every
    required variable is present, and that every value is safe. Optional
    variables the plugin knows a flag for are rendered into the final
    argument; unknown variables are ignored.
    """
    definition = get_plugin_definition(plugin_name)

    if transport is not None and transport not in definition.transports:
        raise PluginConfigurationError(
            f"Plugin '{definition.name}' does not support {transport.value}."
        )

    arguments = []
    for _flag, variable in definition.arguments:
        value = variables.get(variable)
        if value is None or str(value) == "":
            raise PluginConfigurationError(
                f"Plugin '{definition.name}' requires variable '{variable}'."
            )
        arguments.append(validate_variable_value(variable, value))

    options = []
    for variable, flag in definition.options.items():
        value = variables.get(variable)
        if value is None or str(value) == "":
            continue
        options.append(f"{flag} '{validate_variable_value(variable, value)}'")

    arguments.append(" ".join(options))
    return "!".join([definition.command_name] + arguments)


def build_service_checks(plugin_name, variables):
    """
    Expand a plugin's resolved variables into its ServiceChecks, each paired
    with the fully-merged variables for that one service. Returns a list of
    (ServiceCheck, service_variables) tuples.
    """
    definition = get_plugin_definition(plugin_name)
    checks = []
    for check in definition.checks(variables):
        checks.append((check, {**variables, **check.variables}))
    return checks


def render_command_definition(plugin_name):
    """
    Return the Nagios `define command` object for plugin_name.
    """
    definition = get_plugin_definition(plugin_name)
    return COMMAND_TEMPLATE.format(
        command_name=definition.command_name,
        command_line=definition.command_line,
    )


def sanitize_name_part(text):
    """
    Make text safe to use inside a Nagios service_description by replacing
    characters Nagios rejects in object names with "_". Returns "unknown"
    for empty input.
    """
    cleaned = ILLEGAL_NAME_CHARACTERS.sub("_", str(text or "").strip())
    return cleaned or "unknown"
