def _completed(output=""):
    result = MagicMock()
    result.stdout = output
    result.stderr = ""
    result.returncode = 0
    return result


def _write_fake_plugin(directory, name):
    path = os.path.join(directory, name)
    with open(path, "w") as f:
        f.write("#!/bin/sh\necho placeholder\n")
    return path


def _run_by_flag(version_output, help_output):
    """A subprocess.run replacement that answers --version and --help differently."""
    def fake_run(args, **kwargs):
        return _completed(help_output if "--help" in args else version_output)
    return fake_run


_ALWAYS_EXECUTABLE = patch("app.api.plugin.scanner.is_executable", return_value=True)


# ─── catalog ──────────────────────────────────────────────────────────────────

class TestCatalog:
    def test_covers_every_bundled_plugin_with_a_default_command(self):
        missing = sorted(set(PLUGIN_COMMAND_DEFAULTS) - set(PLUGIN_CATALOG))
        assert missing == []

    def test_covers_every_check_plugin_network_discovery_uses(self):
        used = {definition.check_plugin for definition in PLUGIN_DEFINITIONS.values()}
        assert sorted(used - set(PLUGIN_CATALOG)) == []

    def test_covers_plugins_not_listed_in_plugins_list_md(self):
        # check_ftp and check_udp are generated by Network Discovery but are
        # not in Plugins_List.md, so they come from the official manual.
        assert "check_ftp" in PLUGIN_CATALOG
        assert "check_udp" in PLUGIN_CATALOG

    def test_every_entry_is_complete_and_within_column_limits(self):
        for name, entry in PLUGIN_CATALOG.items():
            assert entry["description"].strip(), name
            assert len(entry["description"]) <= MAX_DESCRIPTION_LENGTH, name
            assert entry["category"].strip(), name
            assert len(entry["category"]) <= MAX_CATEGORY_LENGTH, name
            assert entry["documentation_url"].startswith("https://"), name

    def test_ldaps_shares_the_ldap_manual_page(self):
        assert PLUGIN_CATALOG["check_ldaps"]["documentation_url"].endswith("/check_ldap.html")

    def test_ncpa_links_to_the_ncpa_project_not_nagios_plugins(self):
        assert PLUGIN_CATALOG["check_ncpa"]["documentation_url"] == "https://www.nagios.org/ncpa/"

    def test_committed_file_matches_its_generator(self):
        result = subprocess.run(
            [sys.executable, "scripts/build_plugin_descriptions.py", "--check"],
            cwd=SERVER_DIR, capture_output=True, text=True,
        )
        assert result.returncode == 0, result.stdout + result.stderr


